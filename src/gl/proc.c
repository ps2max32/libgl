void (*mxglGetProcAddress(const char *name))(void) {
  int lo = 0, hi = (int)(sizeof procs / sizeof procs[0]) - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2, c = strcmp(name, procs[mid].name);
    if (!c)
      return procs[mid].fn;
    if (c < 0)
      hi = mid - 1;
    else
      lo = mid + 1;
  }
  return NULL;
}
